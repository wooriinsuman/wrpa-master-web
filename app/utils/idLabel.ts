// UUID를 표에 그대로 흘리면 운영자에게는 36자짜리 무의미한 잡음이고, 좁은
// 칸에서는 어차피 말줄임돼 앞뒤 어느 쪽도 읽히지 않는다. 이름을 끝내 찾지
// 못했을 때만 쓰는 최후 표기 — 앞 8자만 남긴다(전체 값은 title로 노출한다).
//
// 이름이 아니라 "짧아진 id"임을 분명히 하려고 생략 기호를 붙인다. 짧은 값
// (uuid가 아닌 코드 등)은 그대로 둔다.
export function shortId(id: string): string {
  return id.length > 12 ? `${id.slice(0, 8)}…` : id
}
